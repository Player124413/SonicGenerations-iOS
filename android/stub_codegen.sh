#!/usr/bin/env bash
# Writes a compile stub for the game code that `rexglue codegen` normally
# generates from the player's default.xex into sonicgenerations/generated/default
# (ignored by git).
#
# The stub carries the same generated surface - {app}_pch.h, {app}_funcs.h,
# {app}_init.h, {app}_init.cpp (PPCImageConfig + PPCFuncMappings),
# {app}_register.cpp and sources.cmake - so the launcher, the SDK tree, the JNI
# layer and the whole Gradle/CMake wiring compile and link without any game
# content. It registers zero guest functions: the app runs, the launcher works,
# but the game itself only builds from a real disc (bash android/build.sh).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
GEN="$HERE/sonicgenerations/generated/default"
# A previous no-disc build may point this at the shipped game code: take the
# link out (never its target) before writing the stub.
[ -L "$GEN" ] && rm "$GEN"
mkdir -p "$GEN"

cat > "$GEN/sonicgenerations_pch.h" <<'EOF'
// Generated by android/stub_codegen.sh for smoke builds (no game) - DO NOT EDIT.
// Compile stand-in for the real rexglue codegen output.
#pragma once

//=============================================================================
// Project Configuration
//=============================================================================

#define REX_CONFIG_H_INCLUDED

#define REX_IMAGE_BASE 0x82000000ull
#define REX_IMAGE_SIZE 0x1000ull
#define REX_CODE_BASE 0x82000000ull
#define REX_CODE_SIZE 0x1000ull
#define REX_THUNK_RESERVE_SIZE 0ull

#define REXCRT_HEAP 0

//=============================================================================
// SDK Headers
//=============================================================================

#include <rex/ppc.h>
#include <rex/image_info.h>

//=============================================================================
// Image Info
//=============================================================================

extern const rex::PPCImageInfo PPCImageConfig;
extern PPCFuncMapping PPCFuncMappings[];

//=============================================================================
// Function Definition Macros
//=============================================================================

#ifndef DECLARE_REX_FUNC
#define DECLARE_REX_FUNC(name) \
  REX_EXTERN(name);            \
  REX_EXTERN(__imp__##name)
#endif
EOF

cat > "$GEN/sonicgenerations_funcs.h" <<'EOF'
// Generated by android/stub_codegen.sh for smoke builds (no game) - DO NOT EDIT.
#pragma once

#include "sonicgenerations_pch.h"

//=============================================================================
// Function Declarations
//=============================================================================
// None: a smoke build registers no guest functions.
EOF

cat > "$GEN/sonicgenerations_init.h" <<'EOF'
// Generated by android/stub_codegen.sh for smoke builds (no game) - DO NOT EDIT.
#pragma once

// The full surface. Recomp files instead take sonicgenerations_pch.h plus a
// per-file declaration header, so a rename cannot invalidate their PCH.
#include "sonicgenerations_pch.h"
#include "sonicgenerations_funcs.h"
EOF

cat > "$GEN/sonicgenerations_init.cpp" <<'EOF'
// Generated by android/stub_codegen.sh for smoke builds (no game) - DO NOT EDIT.

#include "sonicgenerations_init.h"

const rex::PPCImageInfo PPCImageConfig = {
    .code_base = REX_CODE_BASE,
    .code_size = REX_CODE_SIZE,
    .image_base = REX_IMAGE_BASE,
    .image_size = REX_IMAGE_SIZE,
    .func_mappings = PPCFuncMappings,
    .rexcrt_heap = REXCRT_HEAP,
    .codegen_flags = {},
};

PPCFuncMapping PPCFuncMappings[] = {
    {0, nullptr},
};
EOF

cat > "$GEN/sonicgenerations_register.cpp" <<'EOF'
// Generated by android/stub_codegen.sh for smoke builds (no game) - DO NOT EDIT.

#include "sonicgenerations_init.h"

#include <rex/system/function_dispatcher.h>

// Empty: the smoke build registers no guest functions.
void sonicgenerations_RegisterFunctions(rex::runtime::IModuleRegistrar* /*registrar*/) {}
EOF

# NativeXRenderer's hooks call __imp__sub_<addr> (the generated originals).
# The real codegen emits them; here each hooked entry gets an empty one, kept
# in sync with the hook file by grepping it.
{
  echo '// Generated by android/stub_codegen.sh for smoke builds (no game) - DO NOT EDIT.'
  echo '// Empty originals for NativeXRenderer hooks (the real codegen emits them).'
  echo ''
  echo '#include "sonicgenerations_pch.h"'
  echo ''
  grep -oE 'NATIVE_X_RENDERER_HOOK\([0-9A-F]+' "$HERE/../ios/sonicgenerations/src/native_x_renderer_sonicgenerations.cpp" \
    | sed 's/NATIVE_X_RENDERER_HOOK(//' | sort -u | while read -r addr; do
    echo "extern \"C\" void __imp__sub_${addr}([[maybe_unused]] PPCContext& __restrict ctx, [[maybe_unused]] uint8_t* base) {}"
  done
} > "$GEN/sonicgenerations_nativex_stubs.cpp"

cat > "$GEN/sources.cmake" <<'EOF'
# Generated by android/stub_codegen.sh for smoke builds (no game) - DO NOT EDIT.
# Normally written by rexglue codegen from the player's default.xex.

set(GENERATED_SOURCES
    ${CMAKE_CURRENT_LIST_DIR}/sonicgenerations_init.cpp
    ${CMAKE_CURRENT_LIST_DIR}/sonicgenerations_register.cpp
    ${CMAKE_CURRENT_LIST_DIR}/sonicgenerations_nativex_stubs.cpp)
EOF

echo "[android] smoke codegen stub -> $GEN"
